-- Marketplace orders (cash on delivery). ddl-auto=update creates customer_orders and customer_order_items by itself;
-- this file is for environments that run without ddl-auto, plus the one change it can't make.

-- Hibernate's check constraint on notifications.type lists only the types that existed when the table was created,
-- so it rejects the new ORDER type. The app drops it at startup too (OrderSchemaMaintenance).
ALTER TABLE IF EXISTS notifications DROP CONSTRAINT IF EXISTS notifications_type_check;

CREATE TABLE IF NOT EXISTS customer_orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference        VARCHAR(20)    NOT NULL UNIQUE,
    buyer_id         BIGINT         NOT NULL,
    store_id         BIGINT         NOT NULL REFERENCES stores (id),
    status           VARCHAR(20)    NOT NULL,
    payment_method   VARCHAR(30)    NOT NULL,
    customer_name    VARCHAR(100)   NOT NULL,
    customer_phone   VARCHAR(30)    NOT NULL,
    delivery_city    VARCHAR(100)   NOT NULL,
    delivery_address VARCHAR(255)   NOT NULL,
    note             VARCHAR(500),
    subtotal         NUMERIC(15, 2) NOT NULL,
    delivery_fee     NUMERIC(15, 2) NOT NULL,
    total            NUMERIC(15, 2) NOT NULL,
    rejection_reason VARCHAR(255),
    created_at       TIMESTAMP      NOT NULL,
    updated_at       TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_customer_orders_buyer ON customer_orders (buyer_id, created_at);
CREATE INDEX IF NOT EXISTS idx_customer_orders_store ON customer_orders (store_id, status, created_at);

CREATE TABLE IF NOT EXISTS customer_order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES customer_orders (id),
    product_id   BIGINT         NOT NULL REFERENCES products (id),
    product_name VARCHAR(255)   NOT NULL,
    unit_price   NUMERIC(15, 2) NOT NULL,
    quantity     INTEGER        NOT NULL,
    line_total   NUMERIC(15, 2) NOT NULL
);
